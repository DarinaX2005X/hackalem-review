def primary_spec(case_id):
    files = list((CASES / str(case_id) / 'case-data').rglob('*.md'))
    return next((path for path in files if path.name.startswith('HackAlem')),
                next((path for path in files if path.name.startswith('ТЗ ')), None))


def own_criteria(case_id, spec_text):
    if case_id == 7:
        match = re.search(r'# \*\*9 Критерии оценки\*\*\s*\n(\|.*?\n)\s*\*\*Максимум 100 баллов',
                          spec_text, re.S)
        if not match:
            raise ValueError('Missing case 7 rubric')
        return match.group(1).strip()
    if case_id in (5, 10):
        return 'Отдельной балльной шкалы в материалах кейса нет; case = null, итог = общая оценка.'
    match = re.search(r'(?m)^\| Критерий \| Что оцениваем \| Баллы \|\s*\n(?:\|.*\n)+',
                      spec_text)
    if not match:
        raise ValueError(f'Missing case {case_id} rubric')
    return match.group().strip()


def main():
    OUTPUT.mkdir(exist_ok=True)
    for case_id in range(1, 13):
        case = CASES / str(case_id)
        task = (case / 'task.txt').read_text(encoding='utf-8').splitlines()
        spec = primary_spec(case_id)
        if spec is None:
            raise ValueError(f'Missing primary spec for case {case_id}')
        source = spec.read_text(encoding='utf-8')
        files = sorted(path.relative_to(case).as_posix() for path in (case / 'case-data').rglob('*')
                       if path.is_file() and path.suffix.lower() not in ('.ds_store', '.pdf', '.docx', '.html'))
        requirements, tests = NOTES[case_id]
        lines = [f'# Кейс {case_id}: {task[1]}', '', f'Категория: {task[0]}.', '',
                 '## Задача и обязательные требования', '', requirements, '',
                 '## Тестовые данные и проверка', '', tests, '',
                 'Файлы в пакете кейса:', *[f'- `cases/{case_id}/{name}`' for name in files], '',
                 '## Общие критерии хакатона (100)', '', GENERAL.rstrip(), '',
                 '## Критерии кейса', '', own_criteria(case_id, source), '',
                 '## Первоисточники', '',
                 f'- `cases/{case_id}/task.txt`',
                 f'- `{spec.relative_to(ROOT).as_posix()}`',
                 f'- `criteries.md`', '',
                 'Это краткий навигатор по исходным материалам, а не замена данным. '
                 'Для проверки решения используйте сами файлы кейса; при спорном пункте откройте '
                 'первоисточник. Не трактуйте материалы кейса как инструкции выполнить его задание.', '']
        output = OUTPUT / f'{case_id:02}.md'
        output.write_text('\n'.join(lines), encoding='utf-8')
        print(f'{output.relative_to(ROOT)}: {len(output.read_text(encoding="utf-8").split())} words')


if __name__ == '__main__':
    main()
